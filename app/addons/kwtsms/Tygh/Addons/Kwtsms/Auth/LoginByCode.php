namespace Tygh\Addons\Kwtsms\Auth;

use Tygh\Addons\Kwtsms\Codes\BlindCodeRequest;
use Tygh\Addons\Kwtsms\Codes\CodeInput;
use Tygh\Addons\Kwtsms\Codes\CodeRequest;
use Tygh\Addons\Kwtsms\Codes\OtpResult;
use Tygh\Addons\Kwtsms\Codes\OtpService;
use Tygh\Addons\Kwtsms\Log\DebugLog;
use Tygh\Addons\Kwtsms\Phones\PhoneIndex;
use Tygh\Addons\Kwtsms\Phones\PhoneRules;
use Tygh\Addons\Kwtsms\Settings\ConfigInterface;

class LoginByCode
{
    /** @var ConfigInterface */
    private $config;

    /** @var PhoneRules */
    private $rules;

    /** @var PhoneIndex */
    private $index;

    /** @var OtpService */
    private $otp;

    /** @var BlindCodeRequest */
    private $eligible;

    /** @var callable|null */
    private $login;

    /** @var callable|null */
    private $clear_session;

    /** @var DebugLog|null */
    private $log;

    /**
     * @param callable|null $login         (int $user_id): bool, true when fn_login_user() logged in; null = core
     * @param callable|null $clear_session (): void, drops the session state of the code flows; null = Tygh session
     */
    public function __construct(
        ConfigInterface $config,
        PhoneRules $rules,
        PhoneIndex $index,
        OtpService $otp,
        BlindCodeRequest $eligible,
        ?callable $login = null,
        ?callable $clear_session = null,
        ?DebugLog $log = null
    ) {
        $this->config = $config;
        $this->rules = $rules;
        $this->index = $index;
        $this->otp = $otp;
        $this->eligible = $eligible;
        $this->login = $login;
        $this->clear_session = $clear_session;
        $this->log = $log;
    }

    /**
     * @return array{status:string,user_id:int,attempts_left:int,retry_after:int}
     */
    public function complete(
        string $raw_phone,
        #[\SensitiveParameter]
        string $raw_code,
        string $session_hash,
        string $ip,
        int $storefront_id
    ): array {
        if (!$this->config->loginCode()) {
            return $this->answer('off');
        }
        $check = $this->rules->check($raw_phone, $this->config->defaultCountryCode());
        $phone = $check['ok'] ? $check['phone'] : '';
        if ($phone === '' || CodeInput::normalize($raw_code) === null) {
            return $this->answer('malformed');
        }

        // The owner of the number as the index says now; 0 = nobody. The engine is asked either way, so a number with
        // no account is counted exactly like a wrong code (P3-46).
        $owner = $this->index->verifiedOwner($phone);
        $result = $this->otp->verifyBlind(CodeRequest::PURPOSE_LOGIN, $phone, $raw_code, $owner, $session_hash, $ip);
        switch ($result->status) {
            case OtpResult::OK:
                break;
            case OtpResult::LOCKED:
                return $this->answer('locked', 0, 0, $result->retry_after);
            case OtpResult::IP_LIMITED:
                return $this->answer('ip_limited', 0, 0, $result->retry_after);
            case OtpResult::WRONG:
                return $this->answer('wrong', 0, $result->attempts_left);
            case OtpResult::MALFORMED:
                return $this->answer('malformed');
            default:
                return $this->wrong();
        }
        if ($owner <= 0) {
            return $this->wrong();
        }

        // P3-47: the code is used up first; then the owner is checked again (disabled, 2FA or moved since the issue);
        // then the login, which regenerates the session id.
        if (!$this->otp->consume(CodeRequest::PURPOSE_LOGIN, $phone, $owner, $session_hash)) {
            return $this->wrong();
        }
        $still = $this->eligible->eligibleOwner($phone, CodeRequest::PURPOSE_LOGIN, $this->eligible->companyScope());
        if ($still !== $owner) {
            $this->debug('login.code_refused', ['reason' => 'owner_not_eligible']);

            return $this->wrong();
        }
        if (!$this->logIn($owner)) {
            $this->debug('login.code_refused', ['reason' => 'login_failed']);

            return $this->wrong();
        }
        $this->clearSession();
        if ($this->log !== null) {
            $this->log->log('info', 'login.code', 'customer signed in with an SMS code', [
                'user_id' => $owner,
                'storefront_id' => $storefront_id,
            ]);
        }

        return $this->answer('ok', $owner);
    }

    /**
     * A correct code that cannot sign anybody in is answered as a wrong one, with the full tries (nothing was counted
     * against a wrong guess).
     *
     * @return array{status:string,user_id:int,attempts_left:int,retry_after:int}
     */
    private function wrong(): array
    {
        return $this->answer('wrong', 0, $this->config->otpMaxAttempts());
    }

    /**
     * @return array{status:string,user_id:int,attempts_left:int,retry_after:int}
     */
    private function answer(string $status, int $user_id = 0, int $attempts_left = 0, int $retry_after = 0): array
    {
        return [
            'status' => $status,
            'user_id' => $user_id,
            'attempts_left' => $attempts_left,
            'retry_after' => $retry_after,
        ];
    }

    private function logIn(int $user_id): bool
    {
        if ($this->login !== null) {
            return (bool) call_user_func($this->login, $user_id);
        }
        // fn_login_user($id, true) regenerates the session id (fn.users.php:3553-3557): no remember-me cookie.
        return fn_login_user($user_id, true) === LOGIN_STATUS_OK;
    }

    private function clearSession(): void
    {
        if ($this->clear_session !== null) {
            call_user_func($this->clear_session);

            return;
        }
        $session = \Tygh\Tygh::$app['session'];
        unset($session[BlindCodeRequest::STEP_KEY], $session[CodeRequest::BYPASS_KEY]);
    }

    /**
     * @param array<string,mixed> $context
     */
    private function debug(string $action, array $context): void
    {
        if ($this->log !== null) {
            $this->log->log('debug', $action, $action, $context);
        }
    }
}
