 * AUTHOR:    kwtSMS
 * WHAT:      The sign-in by phone and SMS code (P3-46, P3-47): complete() checks the code blind (a phone without an
 *            account, a wrong, expired or foreign-session code all answer the same), consumes it, re-checks that the
 *            owner is still eligible, and only then logs the owner in with fn_login_user($owner, true).
 * WHY:       Task M2.1 (SafatMall B2). This is the account-takeover surface: every doubtful state fails closed
 *            (nobody is logged in), the session id is regenerated by the login (session fixation), the code is bound
 *            to the owner it was issued for and to the requester's session, and no remember-me cookie is ever
 *            written.
 * USAGE:     $login = Tygh::$app['kwtsms.login_by_code'];
 *            $r = $login->complete($raw_phone, $raw_code, $session_hash, $ip, $storefront_id);
 *            $r['status']: ok (the caller is logged in as $r['user_id']), wrong (attempts_left), locked | ip_limited
 *            (retry_after), malformed (the phone or the code is not well formed; nothing counted), off (login_code is
 *            OFF). Anything else is wrong. A "wrong" also answers a correct code whose owner is no longer eligible
 *            (disabled, 2FA, ambiguous, moved to another account since the code was issued).
 *            Test seams (constructor): $login (int $user_id): bool, $clear_session (): void.
 * DEPENDS:   Settings\ConfigInterface, Phones\{PhoneRules,PhoneIndex}, Codes\{OtpService,OtpResult,CodeInput,
 *            BlindCodeRequest,CodeRequest}, Log\DebugLog (optional), core fn_login_user(), LOGIN_STATUS_OK.
